// ── Build lookup maps ─────────────────────────────────────────────────────────
const buildMap = (table) => {
  const map = {};
  for (const [key, L, M, S] of table) map[key] = { L, M, S };
  return map;
};

const LMS = {
  wfa: { male: buildMap(WFA_LMS.male), female: buildMap(WFA_LMS.female) },
  hfa: { male: buildMap(HFA_LMS.male), female: buildMap(HFA_LMS.female) },
  wfh: { male: buildMap(WFL_LMS.male), female: buildMap(WFL_LMS.female) },
};

// ── Helpers ───────────────────────────────────────────────────────────────────
/**
 * Interpolate for age/length keys not in the table
 */
const interpolate = (map, key) => {
  const keys = Object.keys(map).map(Number).sort((a, b) => a - b);
  if (key <= keys[0])  return map[keys[0]];
  if (key >= keys[keys.length - 1]) return map[keys[keys.length - 1]];

  let lo = keys[0], hi = keys[1];
  for (let i = 0; i < keys.length - 1; i++) {
    if (keys[i] <= key && key <= keys[i + 1]) { lo = keys[i]; hi = keys[i + 1]; break; }
  }
  const t = (key - lo) / (hi - lo);
  const a = map[lo], b = map[hi];
  return {
    L: a.L + (b.L - a.L) * t,
    M: a.M + (b.M - a.M) * t,
    S: a.S + (b.S - a.S) * t,
  };
};

/**
 * WHO LMS z-score formula
 * z = ((X/M)^L - 1) / (L * S)   if L != 0
 * z = ln(X/M) / S               if L = 0
 */
const lmsZ = (X, L, M, S) => {
  if (Math.abs(L) < 1e-6) return Math.log(X / M) / S;
  return (Math.pow(X / M, L) - 1) / (L * S);
};

const clampZ = (z) => Math.max(-6, Math.min(6, z));

const classify = (z) => {
  if (z < -3.0) return 'severe';
  if (z < -2.0) return 'severe';
  if (z < -1.0) return 'moderate';
  return 'healthy';
};

// ── Core exports ──────────────────────────────────────────────────────────────
/**
 * Calculate Weight-for-Age Z-score (WAZ)
 */
const computeWAZ = (weight, ageMonths, gender) => {
  const map = LMS.wfa[gender === 'male' ? 'male' : 'female'];
  const { L, M, S } = interpolate(map, Math.min(60, Math.max(0, ageMonths)));
  return parseFloat(clampZ(lmsZ(weight, L, M, S)).toFixed(2));
};

/**
 * Calculate Height/Length-for-Age Z-score (HAZ)
 */
const computeHAZ = (height, ageMonths, gender) => {
  const map = LMS.hfa[gender === 'male' ? 'male' : 'female'];
  const { L, M, S } = interpolate(map, Math.min(60, Math.max(0, ageMonths)));
  return parseFloat(clampZ(lmsZ(height, L, M, S)).toFixed(2));
};

/**
 * Calculate Weight-for-Height/Length Z-score (WHZ)
 * Uses 0.5 cm grid; clamp to table range 45–110 cm
 */
const computeWHZ = (weight, height, gender) => {
  const map = LMS.wfh[gender === 'male' ? 'male' : 'female'];
  const lengthKey = Math.round(Math.min(110, Math.max(45, height)) * 2) / 2; // round to nearest 0.5
  const { L, M, S } = interpolate(map, lengthKey);
  return parseFloat(clampZ(lmsZ(weight, L, M, S)).toFixed(2));
};

/**
 * Predict malnutrition using WHO z-scores
 * @param {number} weight   - kg
 * @param {number} height   - cm
 * @param {number} ageMonths
 * @param {string} gender   - 'male' | 'female'
 */
const predictMalnutrition = (weight, height, ageMonths, gender) => {
  const waz = computeWAZ(weight, ageMonths, gender);
  const haz = computeHAZ(height, ageMonths, gender);
  const whz = computeWHZ(weight, height, gender);

  const wazStatus = classify(waz);
  const hazStatus = classify(haz);
  const whzStatus = classify(whz);

  const statuses = [wazStatus, hazStatus, whzStatus];
  const prediction = statuses.includes('severe')
    ? 'severe'
    : statuses.includes('moderate')
    ? 'moderate'
    : 'healthy';

  const advice =
    prediction === 'severe'
      ? 'Severe malnutrition detected. Immediate referral to Primary Health Centre (PHC) required. Begin therapeutic nutrition support.'
      : prediction === 'moderate'
      ? 'Moderate nutritional risk. ASHA follow-up, dietary counselling and iron/vitamin A supplementation recommended.'
      : 'Child is growing normally. Continue routine check-ups and exclusive breastfeeding.';

  return { waz, haz, whz, wazStatus, hazStatus, whzStatus, prediction, advice };
};

module.exports = { predictMalnutrition, computeWAZ, computeHAZ, computeWHZ, classify };
